def robustness_macros(m):
    pc_path = FIG / "simclr" / "positive_controls.csv"
    if not pc_path.exists():
        return
    m.lines.append("% Robustness: positive controls, probes and encoders (simclr, core_*, drivers_*)")
    pc = pd.read_csv(pc_path).set_index("run")
    for run, tag in [("harmonized_physical", "Astro"), ("simclr_mocks", "SimM"), ("simclr_lemur", "SimL")]:
        if run in pc.index:
            r = pc.loc[run]
            m.add(f"pcMass{tag}", fmt(r["R2_logM500_mocks"]))
            m.add(f"pcTcool{tag}", fmt(r["R2_logtcool_TNGCluster"]))
            m.add(f"pcConc{tag}", fmt(r["R2_logc_all"]))
            m.add(f"pcHalo{tag}", f"{100 * r['same_halo_nn_fraction']:.0f}")
    ps_rho, exp_rho = [], []
    for tag, label, core_dir, config, drivers_dir in REPRESENTATIONS:
        core_csv = FIG / core_dir / "core_auc.csv"
        if core_csv.exists():
            c = pd.read_csv(core_csv)
            c = c[c["config"] == config]
            vals = []
            for _, r in c.iterrows():
                key = SIMTAG[r["pair"].replace("LEMUR vs ", "")] + ZTAG[round(r["redshift"], 2)]
                m.auc(f"aucLc{tag}{key}", r["auc_L_c"], r["auc_L_c_lo"], r["auc_L_c_hi"])
                vals.append(r["auc_L_c"])
            m.add(f"aucLcRange{tag}", span(min(vals), max(vals)))
            if "null_mean_L_c" in c and c["null_mean_L_c"].notna().all():
                excess = c["auc_L_c"] - c["null_mean_L_c"]
                m.add(f"excessLcRange{tag}", f"{excess.min():+.2f} to {excess.max():+.2f}")
        match_csv = FIG / drivers_dir / "drivers_matching.csv"
        if match_csv.exists():
            d = pd.read_csv(match_csv)
            full = d[d["matched_on"] == FULL]
            if len(full):
                m.add(f"aucFullRange{tag}", span(full["auc"].min(), full["auc"].max()))
                if "null_mean" in full:
                    excess = full["auc"] - full["null_mean"]
                    m.add(f"excessFullRange{tag}", f"{excess.min():+.2f} to {excess.max():+.2f}")
                    for _, r in full.iterrows():
                        key = SIMTAG[r["sim"]] + ZTAG[round(r["redshift"], 2)]
                        m.auc(f"aucFull{tag}{key}", r["auc"], r["auc_lo"], r["auc_hi"])
                        m.add(f"nullFull{tag}{key}", f"{fmt(r['null_mean'])}\\,[{fmt(r['null_lo'])},\\,{fmt(r['null_hi'])}]")
            if "null_lo" in full:
                inside = ((full["auc"] >= full["null_lo"] - (full["auc_hi"] - full["auc"])) &
                          (full["auc"] <= full["null_hi"] + (full["auc"] - full["auc_lo"])))
                m.add(f"nFullInNull{tag}", str(int(inside.sum())))
                m.add(f"nullFullRange{tag}", f"{full['null_mean'].min():.2f}--{full['null_mean'].max():.2f}")
        corr_csv = FIG / drivers_dir / "drivers_correlations.csv"
        if corr_csv.exists():
            k = pd.read_csv(corr_csv).set_index("column")
            ps_rho.append(k.loc["ps_fraction", "spearman_rho"])
            exp_rho.append(k.loc["log_exposure", "spearman_rho"])
    if ps_rho:
        m.add("rhoPointSources", span(min(ps_rho), max(ps_rho)))
        m.add("rhoExposure", f"{min(exp_rho):.2f} to {max(exp_rho):.2f}")
    # Significance of each matched AUC against its null: (AUC - null mean) /
    # sqrt(bootstrap half-width^2 + null half-width^2), the 68% half-widths.
    within1 = within2 = total = 0
    outliers = []
    for tag, label, core_dir, config, drivers_dir in REPRESENTATIONS:
        c = pd.read_csv(FIG / core_dir / "core_auc.csv")
        c = c[c["config"] == config]
        if "null_mean_L_c" in c and c["null_mean_L_c"].notna().all():
            sig = np.sqrt(((c["auc_L_c_hi"] - c["auc_L_c_lo"]) / 2) ** 2 + ((c["null_hi_L_c"] - c["null_lo_L_c"]) / 2) ** 2)
            zs = (c["auc_L_c"] - c["null_mean_L_c"]) / sig
            m.add(f"sigLcMax{tag}", f"{zs.max():.1f}")
            m.add(f"sigLcRange{tag}", f"{zs.min():.1f} to {zs.max():.1f}")
        d = pd.read_csv(FIG / drivers_dir / "drivers_matching.csv")
        f = d[d["matched_on"] == FULL]
        if "null_mean" in f and f["null_mean"].notna().all():
            sig = np.sqrt(((f["auc_hi"] - f["auc_lo"]) / 2) ** 2 + ((f["null_hi"] - f["null_lo"]) / 2) ** 2)
            signed = (f["auc"] - f["null_mean"]) / sig
            zs = signed.abs()
            for (_, r), zz in zip(f.iterrows(), signed):
                if abs(zz) > 2:
                    outliers.append(f"{label} against {r['sim'].replace('TNG300-1', 'TNG300')} at $z = {r['redshift']:g}$ (${zz:+.1f}\\sigma$)")
            within1 += int((zs <= 1).sum())
            within2 += int((zs <= 2).sum())
            total += len(zs)
    if total:
        m.add("nFullTotal", str(total))
        m.add("nFullWithinOne", str(within1))
        m.add("nFullWithinTwo", str(within2))
        m.add("fullOutliers", "; ".join(outliers) if outliers else "none")


def agn_macros(m):
    """Central point sources and high-c fractions with bootstrap intervals (domain_gap.agn)."""
    summary_csv, table_csv = FIG / "agn" / "summary.csv", FIG / "agn" / "high_c_fractions.csv"
    if not (summary_csv.exists() and table_csv.exists()):
        return
    m.lines.append("% AGN check and high-c fractions with 68% bootstrap intervals (agn)")
    summary = pd.read_csv(summary_csv, index_col=0).iloc[:, 0]
    for key, name in [("lemur_flagged", "nAgnFlagged"), ("lemur_with_spike", "nAgnMeasured"),
                      ("high_c_flagged", "nHighcFlagged"), ("high_c", "nHighc")]:
        m.add(name, str(int(summary[key])))
    m.add("rhoCvsCmasked", fmt(float(summary["rho_c_vs_c_masked_lemur"])))
    t = pd.read_csv(table_csv)
    subs = {"all": "All", "in PSZ2": "PSZ", "not in PSZ2": "NotPSZ"}
    variants = {"c": "C", "c_masked": "Masked", "c, central point sources removed": "NoAgn"}

    def pct(v, lo, hi):
        return f"{100 * v:.0f}\\,[{100 * lo:.0f},\\,{100 * hi:.0f}]"

    plain = t[t["variant"] == "c"].pivot_table(index="redshift", columns="lemur", values="lemur_frac")
    ratio = plain["not in PSZ2"] / plain["in PSZ2"]
    m.add("selectionRatioRange", f"{ratio.min():.1f}--{ratio.max():.1f}")
    for _, r in t.iterrows():
        tag = subs[r["lemur"]] + variants[r["variant"]] + ZTAG[round(r["redshift"], 2)]
        m.add(f"fHigh{tag}", pct(r["lemur_frac"], r["lemur_lo"], r["lemur_hi"]))
        m.add(f"fHighMock{tag}", pct(r["mock_frac"], r["mock_lo"], r["mock_hi"]))
        m.add(f"pHigh{tag}", pval(r["p_lemur_not_higher"]))
        m.add(f"nHigh{tag}", str(int(r["n_lemur"])))


def significance(v, lo, hi, null_mean, null_lo, null_hi):
    """(AUC - null mean) / sqrt(bootstrap half-width^2 + null half-width^2)."""
    return (v - null_mean) / np.sqrt(((hi - lo) / 2) ** 2 + ((null_hi - null_lo) / 2) ** 2)


