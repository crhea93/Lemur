def span(lo, hi, digits=2):
    """'lo--hi', or one value when both round the same."""
    a, b = f"{lo:.{digits}f}", f"{hi:.{digits}f}"
    return a if a == b else f"{a}--{b}"


def fmt(v, digits=2):
    return "--" if v is None or not np.isfinite(v) else f"{v:.{digits}f}"


class Macros:
    def __init__(self):
        self.lines = []

    def add(self, name, value, comment=None):
        if comment:
            self.lines.append(f"% {comment}")
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def auc(self, name, v, lo, hi):
        self.add(name, fmt(v))
        self.add(name + "Err", f"{fmt(v)}\\,[{fmt(lo)},\\,{fmt(hi)}]")

    def write(self, path):
        Path(path).write_text("% Generated by python -m domain_gap.paper; do not edit.\n" + "\n".join(self.lines) + "\n")


def sample_macros(m):
    man = pd.read_parquet(EMB / "harmonized_physical" / "manifest.parquet")
    base = pd.read_parquet(EMB / "baseline" / "manifest.parquet")
    lemur = man[man["source"] == "LEMUR"]
    m.add("nLemurClusters", f"{len(base[base['source'] == 'LEMUR']):,}", "Samples")
    m.add("nLemurWithZ", f"{int(lemur['redshift'].notna().sum()):,}")
    m.add("nLemurUsable", f"{int(lemur['usable'].sum()):,}")
    sig = pd.read_csv(FIG / "signal" / "signal.csv")
    s = sig[sig["source"] == "LEMUR"]
    m.add("nLemurPassSignal", f"{int(((s['snr'] >= 10) & ~(s['ps_fraction'] > 0.5)).sum()):,}")
    m.add("nLemurLowSN", f"{int((s['snr'] < 10).sum()):,}")
    m.add("nLemurPointSource", f"{int((s['ps_fraction'] > 0.5).sum()):,}")
    mocks = man[man["source"] != "LEMUR"]
    m.add("nMockHalos", f"{mocks.groupby(['source', 'halo_id']).ngroups:,}")
    m.add("nMockHalosTNGthree", f"{mocks[mocks['source'] == 'TNG300-1']['halo_id'].nunique():,}")
    m.add("nMockHalosTNGC", f"{mocks[mocks['source'] == 'TNG-Cluster']['halo_id'].nunique():,}")
    m.add("nMockImages", f"{len(mocks):,}")
    for sim, tag in SIMTAG.items():
        mm = mocks[mocks["source"] == sim].drop_duplicates("halo_id")["M500c_Msun"]
        m.add(f"medMfiveTNG{tag[3:]}", fmt(np.log10(mm.median()), 1))


def original_macros(m):
    o = pd.read_csv(FIG / "original" / "original_gap.csv")
    names = ["Original", "Regenerated", "Morphology", "Physical"]
    cols = {"TNGthree": "LEMUR vs TNG300-1", "TNGC": "LEMUR vs TNG-Cluster", "Sims": "TNG-Cluster vs TNG300-1", "SimsEqualM": "TNG-Cluster vs TNG300-1 (equal M500)"}
    m.lines.append("% Step sequence at z = 0.05 (original_gap)")
    for name, (_, row) in zip(names, o.iterrows()):
        for tag, col in cols.items():
            m.auc(f"auc{name}{tag}", row[col], row[col + "_lo"], row[col + "_hi"])


def core_macros(m):
    c = pd.read_csv(FIG / "core" / "core_auc.csv")
    c = c[c["config"] == "harmonized_physical"]
    m.lines.append("% Physical config: L-matched and (L, c)-matched AUCs and permutation nulls (core)")
    for _, r in c.iterrows():
        tag = SIMTAG[r["pair"].replace("LEMUR vs ", "")] + ZTAG[round(r["redshift"], 2)]
        m.auc(f"aucL{tag}", r["auc_L"], r["auc_L_lo"], r["auc_L_hi"])
        m.auc(f"aucLc{tag}", r["auc_L_c"], r["auc_L_c_lo"], r["auc_L_c_hi"])
        if "null_mean_L_c" in r and np.isfinite(r["null_mean_L_c"]):
            m.add(f"null{tag}", f"{fmt(r['null_mean_L_c'])}\\,[{fmt(r['null_lo_L_c'])},\\,{fmt(r['null_hi_L_c'])}]")
        m.add(f"nLemurLc{tag}", str(int(r["n_lemur_L_c"])))
    med = pd.read_csv(FIG / "core" / "core_medians.csv")
    for _, r in med.iterrows():
        tag = SIMTAG[r["sim"]] + ZTAG[round(r["redshift"], 2)]
        m.add(f"medcLemur{tag}", fmt(r["lemur_median_c"], 3))
        m.add(f"medcMock{tag}", fmt(r["mock_median_c"], 3))


def mass_macros(m):
    t = pd.read_csv(FIG / "mass" / "matched_auc.csv")
    t = t[t["config"] == "harmonized_physical"]
    m.lines.append("% Mass matching (mass_match, physical config)")
    for _, r in t.iterrows():
        z = ZTAG[round(r["redshift"], 2)]
        if r["pair"].startswith("TNG-Cluster vs"):
            m.auc(f"aucSimsAll{z}", r["auc_all"], r["auc_all_lo"], r["auc_all_hi"])
            m.auc(f"aucSimsEqualM{z}", r["auc_matched"], r["auc_matched_lo"], r["auc_matched_hi"])
        else:
            tag = SIMTAG[r["pair"].replace("LEMUR vs ", "")] + z
            m.auc(f"aucAll{tag}", r["auc_all"], r["auc_all_lo"], r["auc_all_hi"])
    # L-M relation of the mocks.
    from . import mass_match as mmod

    lum = pd.read_csv(FIG / "mass" / "luminosities.csv")
    man = pd.read_parquet(EMB / "harmonized_physical" / "manifest.parquet").merge(lum[["source", "name", "log_L_ph"]], on=["source", "name"])
    slopes, scatters = [], []
    for z in (0.05, 0.1, 0.2):
        a, b, pivot, scatter = mmod.fit_lm(man[(man["source"] != "LEMUR") & (man["redshift"] == z)])
        slopes.append(b)
        scatters.append(scatter)
    m.add("lmSlope", fmt(np.mean(slopes)))
    m.add("lmScatter", f"{fmt(min(scatters))}--{fmt(max(scatters))}")


def selection_macros(m):
    s = pd.read_csv(FIG / "selection" / "selection_core.csv")
    matches = pd.read_csv(FIG / "selection" / "lemur_catalog_matches.csv")
    with_z = matches[matches["redshift"].notna()]
    m.add("nLemurPSZ", str(int(with_z["in_psz2"].sum())), "Selection (selection)")
    m.add("nLemurMCXC", str(int(with_z["in_mcxc"].sum())))
    masses = pd.read_csv(FIG / "mass" / "lemur_masses.csv").merge(matches, on="name")
    for col, tag in [("log_M_SZ", "PSZ"), ("log_M_MCXC", "MCXC")]:
        d = (masses["log_M500_est"] - masses[col]).dropna()
        m.add(f"massOffset{tag}", f"{d.median():+.2f}")
        m.add(f"massScatter{tag}", fmt(1.4826 * (d - d.median()).abs().median()))
        m.add(f"nMassCheck{tag}", str(len(d)))
    for label, tag in [("in PSZ2", "PSZ"), ("not in PSZ2", "NotPSZ"), ("all", "All")]:
        for z, zt in ZTAG.items():
            r = s[(s["lemur"] == label) & (np.isclose(s["redshift"], z))]
            if len(r):
                m.add(f"fHighc{tag}{zt}", f"{100 * r['lemur_frac_high_c'].mean():.0f}")
    for z, zt in ZTAG.items():
        r = s[(s["lemur"] == "all") & (np.isclose(s["redshift"], z))]
        lo, hi = (f"{100 * v:.0f}" for v in (r["mock_frac_high_c"].min(), r["mock_frac_high_c"].max()))
        m.add(f"fHighcMock{zt}", lo if lo == hi else f"{lo}--{hi}")


def concentration_macros(m):
    from scipy.stats import spearmanr

    core = pd.read_csv(FIG / "core" / "core.csv")
    man = pd.read_parquet(EMB / "harmonized_physical" / "manifest.parquet").merge(core, on=["source", "name"])
    labels = pd.read_csv(ROOT / "configs" / "halos" / "tng_cluster.csv")
    cl = man[(man["source"] == "TNG-Cluster") & (man["exposure_ks"] == 100)].merge(labels, on="halo_id")
    for z, zt in ZTAG.items():
        h = cl[cl["redshift"] == z].groupby("halo_id").agg(c=("c40_250", "median"), t=("central_cooling_time_gyr_z0", "first"))
        m.add(f"rhoTcool{zt}", fmt(spearmanr(np.log10(h["t"]), h["c"], nan_policy="omit")[0]))


def observational_macros(m):
    path = FIG / "observational" / "observational.csv"
    if not path.exists():
        # Placeholders so the paper compiles before the analysis has run.
        m.lines.append("% Observational effects: not run yet")
        for z in ZTAG.values():
            m.add(f"aucExpMocks{z}", "\\todo{pending}")
        for key in ("distExposure", "distProjection", "distHalo"):
            m.add(key, "\\todo{pending}")
        return
    t = pd.read_csv(path)
    t = t[t["config"] == "harmonized_physical"]
    m.lines.append("% Observational effects (observational, physical config)")
    for _, r in t.iterrows():
        key = {
            "LEMUR: has ACIS-S data vs not": "InstrLemur",
            "LEMUR: more than one ObsID vs not": "MosaicLemur",
            "LEMUR: exposure above median vs not": "ExpLemur",
            "vs mocks: all LEMUR": "VsMocksAll",
            "vs mocks: has ACIS-S data": "VsMocksAcisS",
            "vs mocks: not has ACIS-S data": "VsMocksAcisI",
            "vs mocks: more than one ObsID": "VsMocksMosaic",
            "vs mocks: not more than one ObsID": "VsMocksSingle",
            "vs mocks: exposure above median": "VsMocksDeep",
            "vs mocks: not exposure above median": "VsMocksShallow",
        }.get(r["test"])
        if r["test"].startswith("mocks: 20 vs 100"):
            key = "ExpMocks" + ZTAG[round(r["redshift"], 2)]
        if key:
            m.auc(f"auc{key}", r["auc"], r["auc_lo"], r["auc_hi"])
            if "null_mean" in r and np.isfinite(r.get("null_mean", np.nan)):
                m.add(f"null{key}", f"{fmt(r['null_mean'])}\\,[{fmt(r['null_lo'])},\\,{fmt(r['null_hi'])}]")
    pairs = pd.read_csv(FIG / "observational" / "exposure_pairs.csv")
    for config, suffix, digits in [("harmonized_physical", "", 3), ("harmonized_morphology", "Morph", 2), ("baseline", "Base", 2)]:
        p = pairs[pairs["config"] == config]
        for col, key in [("same_halo_20_vs_100ks", "distExposure"), ("same_halo_other_projection", "distProjection"), ("other_halo_same_mass", "distHalo")]:
            m.add(key + suffix, span(p[col].min(), p[col].max(), digits))
    morph = pd.read_csv(path)
    morph = morph[(morph["config"] == "harmonized_morphology") & morph["test"].str.startswith("mocks: 20 vs 100")]
    m.add("aucExpMocksMorph", span(morph["auc"].min(), morph["auc"].max()))


def waterfall(out):
    """AUC at each step at z = 0.05, with the permutation null of the last step."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    o = pd.read_csv(FIG / "original" / "original_gap.csv")
    c = pd.read_csv(FIG / "core" / "core_auc.csv")
    c = c[(c["config"] == "harmonized_physical")]
    steps = ["Original\nmocks", "Regenerated\nmocks", "Harmonized\n(physical)", "+ matched\n$L$, exposure", "+ matched\nconcentration"]
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.0), gridspec_kw={"width_ratios": [1.6, 1]}, sharey=True)
    ax = axes[0]
    for sim, color, dx in [("TNG300-1", "tab:blue", -0.08), ("TNG-Cluster", "tab:red", 0.08)]:
        col = f"LEMUR vs {sim}"
        r = c[(c["pair"] == col) & np.isclose(c["redshift"], 0.05)].iloc[0]
        vals = [o[col].iloc[0], o[col].iloc[1], o[col].iloc[3], r["auc_L"], r["auc_L_c"]]
        lo = [o[col + "_lo"].iloc[0], o[col + "_lo"].iloc[1], o[col + "_lo"].iloc[3], r["auc_L_lo"], r["auc_L_c_lo"]]
        hi = [o[col + "_hi"].iloc[0], o[col + "_hi"].iloc[1], o[col + "_hi"].iloc[3], r["auc_L_hi"], r["auc_L_c_hi"]]
        x = np.arange(len(steps)) + dx
        ax.errorbar(x, vals, yerr=[np.subtract(vals, lo), np.subtract(hi, vals)], fmt="o-", color=color, ms=4, lw=1, capsize=2, label=f"LEMUR vs {sim}")
        if "null_lo_L_c" in r:
            ax.fill_between([len(steps) - 1.35, len(steps) - 0.65], r["null_lo_L_c"], r["null_hi_L_c"], color=color, alpha=0.12, lw=0)
    ax.axhline(0.5, color="gray", ls="--", lw=0.8)
    ax.set_xticks(np.arange(len(steps)), steps, fontsize=7)
    ax.set_ylabel("domain classifier AUC")
    ax.set_title("$z = 0.05$", fontsize=9)
    ax.set_ylim(0.3, 1.03)
    ax.legend(fontsize=7, loc="lower left")
    ax = axes[1]
    zs = [0.05, 0.1, 0.2]
    for sim, color, dx in [("TNG300-1", "tab:blue", -0.08), ("TNG-Cluster", "tab:red", 0.08)]:
        r = c[c["pair"] == f"LEMUR vs {sim}"].set_index("redshift")
        x = np.arange(len(zs)) + dx
        for key, marker, fill in [("auc_L", "o", "none"), ("auc_L_c", "o", color)]:
            v = [r.loc[z, key] for z in zs]
            ax.errorbar(x, v, yerr=[[r.loc[z, key] - r.loc[z, key + "_lo"] for z in zs], [r.loc[z, key + "_hi"] - r.loc[z, key] for z in zs]],
                        fmt=marker, color=color, mfc=fill, ms=4, capsize=2, lw=1)
        if "null_lo_L_c" in r:
            for i, z in enumerate(zs):
                ax.fill_between([i + dx - 0.12, i + dx + 0.12], r.loc[z, "null_lo_L_c"], r.loc[z, "null_hi_L_c"], color=color, alpha=0.12, lw=0)
    ax.axhline(0.5, color="gray", ls="--", lw=0.8)
    ax.set_xticks(np.arange(len(zs)), [f"$z={z:g}$" for z in zs], fontsize=8)
    ax.plot([], [], "o", mfc="none", color="k", label="matched $L$, exposure")
    ax.plot([], [], "o", color="k", label="+ concentration")
    ax.legend(fontsize=7, loc="upper right")
    ax.set_title("harmonized physical, all redshifts", fontsize=9)
    fig.tight_layout()
    fig.savefig(out / "waterfall.pdf")
    fig.savefig(out / "waterfall.png", dpi=150)
    plt.close(fig)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--paper", default=str(ROOT / "paper"))
    args = parser.parse_args(argv)
    paper = Path(args.paper)
    figures = paper / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    m = Macros()
    for part in (sample_macros, original_macros, core_macros, mass_macros, selection_macros, concentration_macros, observational_macros):
        part(m)
    m.write(paper / "macros.tex")
    waterfall(figures)
    copied = 0
    for src, dst in COPY.items():
        if (FIG / src).exists():
            shutil.copy2(FIG / src, figures / dst)
            copied += 1
    print(f"Wrote {paper / 'macros.tex'} ({sum(l.startswith(chr(92)) for l in m.lines)} macros), waterfall, {copied} figures")
    return 0


if __name__ == "__main__":
    sys.exit(main())
