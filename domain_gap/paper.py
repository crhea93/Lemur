def math_safe(value):
    """A macro value that typesets the same in text and in math: signed
    numbers as math (a true minus sign), range dashes and ' to ' as text."""
    value = re.sub(r"(?<![\w.\-])([+-]\d+(?:\.\d+)?)", r"\\ensuremath{\1}", str(value))
    return value.replace("--", "\\mbox{--}").replace(" to ", "\\mbox{ to }")


def pval(p):
    """A p-value with its relation, for '$p \\pX$'."""
    return "< 0.001" if p < 0.001 else f"= {p:.3f}"


def span(lo, hi, digits=2):
    """'lo--hi', or one value when both round the same."""
    a, b = f"{lo:.{digits}f}", f"{hi:.{digits}f}"
    return a if a == b else f"{a}--{b}"


def fmt(v, digits=2):
    return "--" if v is None or not np.isfinite(v) else f"{v:.{digits}f}"


class Macros:
    def __init__(self):
        self.lines = []

    def add(self, name, value, comment=None):
        if comment:
            self.lines.append(f"% {comment}")
        self.lines.append(f"\\newcommand{{\\{name}}}{{{math_safe(value)}}}")

    def auc(self, name, v, lo, hi):
        self.add(name, fmt(v))
        self.add(name + "Err", f"{fmt(v)}\\,[{fmt(lo)},\\,{fmt(hi)}]")

    def write(self, path):
        Path(path).write_text("% Generated by python -m domain_gap.paper; do not edit.\n" + "\n".join(self.lines) + "\n")


