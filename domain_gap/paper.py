"""Numbers and figures for the paper, from the analysis outputs.

    python -m domain_gap.paper [--paper paper]

Writes {paper}/macros.tex (every number quoted in the text, as LaTeX macros,
so a rerun of any analysis updates the paper), the headline figure
{paper}/figures/waterfall.pdf, and copies the other figures into
{paper}/figures/. Run after domain_gap.original_gap, core (with --null),
mass_match, selection and observational.

Macro names spell out numbers: TNGthree = TNG300, TNGC = TNG-Cluster;
zA, zB, zC = z 0.05, 0.1, 0.2.
"""

